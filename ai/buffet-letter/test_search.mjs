import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {makeKeywordIndex,rankKeywords,rankVectors,eligible,distinctResults} from './dist/search-core.mjs';
const {chunks,metadata}=JSON.parse(readFileSync('./dist/corpus.json','utf8'));
assert.equal(metadata.documents.length,49);
assert.deepEqual(metadata.documents.map(d=>d.year),Array.from({length:49},(_,i)=>1977+i));
assert.equal(metadata.missing.length,0);
const f={from:1977,to:2024,author:'Warren Buffett',contains:''};
const index=makeKeywordIndex(chunks);
const result=rankKeywords(chunks,index,'insurance float',f);
assert.ok(result.length>20);
assert.ok(result.slice(0,5).every(r=>chunks[r.index].text.toLowerCase().includes('float')));
assert.ok(result.every(r=>eligible(chunks[r.index],f)));
const geico=rankKeywords(chunks,index,'insurance',{...f,from:2000,to:2010,contains:'GEICO'});
assert.ok(geico.length>0);
assert.ok(geico.every(r=>chunks[r.index].text.includes('GEICO')&&chunks[r.index].year>=2000&&chunks[r.index].year<=2010));
assert.equal(rankKeywords(chunks,index,'zzzxxyyunknownword',f).length,0);
assert.ok(chunks.filter(c=>c.year===2025).every(c=>c.author==='Greg Abel'));
assert.ok(chunks.filter(c=>c.year===2014&&c.page>=38).every(c=>c.author==='Charlie Munger'));
const bytes=readFileSync('./dist/vectors.f32');const vectors=new Float32Array(bytes.buffer,bytes.byteOffset,bytes.byteLength/4);
assert.equal(vectors.length,chunks.length*384);
const target=chunks.findIndex(c=>c.author==='Warren Buffett'&&c.text.toLowerCase().includes('insurance float'));
const similarity=rankVectors(chunks,vectors,vectors.subarray(target*384,(target+1)*384),f);
assert.equal(similarity[0].index,target);assert.ok(similarity[0].score>.999);
assert.ok(distinctResults(result,chunks).length<=40);
console.log(JSON.stringify({passed:true,letters:metadata.documents.length,passages:chunks.length,keyword_top_year:chunks[result[0].index].year}));
